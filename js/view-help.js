export function renderHelp(root){
  injectStyles();
  root.innerHTML = '';
  root.appendChild(el('<div class="h1">Инструкция</div>'));
  root.appendChild(el('<p class="muted" style="margin:0 0 16px">Как установить приложение и работать с ним. Эту же инструкцию можно распечатать.</p>'));
  const wrap = document.createElement('div');
  wrap.innerHTML = helpBodyHtml();
  while (wrap.firstChild) root.appendChild(wrap.firstChild);
}
